/// Maps a reverse-geocoded name ("Dhaka District", "Chittagong", "যশোর জেলা") to a district id, or
/// null when it isn't recognisably a district. The server falls back to the nearest district.
String? districtIdFromName(String? name) {
  if (name == null) return null;
  final bnKey = name.replaceAll('জেলা', '').trim();
  if (_bnNames.containsKey(bnKey)) return _bnNames[bnKey];
  final slug = name
      .toLowerCase()
      .replaceAll("'", '')
      .replaceAll(RegExp(r'\b(district|zila|zilla|division)\b'), '')
      .replaceAll(RegExp(r'[^a-z]+'), '-')
      .replaceAll(RegExp(r'^-+|-+$'), '');
  if (districtIds.contains(slug)) return slug;
  return _aliases[slug];
}
